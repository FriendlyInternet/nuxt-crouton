<script setup lang="ts">
import type { InboxCardFormProps, InboxCardFormData } from '../../types'
import useInboxCards from '../composables/useInboxCards'

const props = defineProps<InboxCardFormProps>()
const { defaultValue, schema, collection } = useInboxCards()

// Field labels resolve through translations (team override → system → fallback)
const { t } = useT()

// Form layout configuration


// Static select options
