const MARKER_LINE = /^<!--.*-->$/

/** Lines from the top of `body` that are hidden `<!-- … -->` markers, stopping at the first other line. */
export function leadingMarkers(body: string | null | undefined): string[] {
  const out: string[] = []
  for (const l of String(body ?? '').replace(/^\uFEFF/, '').split(/\r?\n/)) {
    const t = l.trim()
    if (!MARKER_LINE.test(t)) break
    out.push(t)
  }
  return out
}

export const hasMarker = (body: string | null | undefined, marker: string) => leadingMarkers(body).includes(marker)

export function markerValue(body: string | null | undefined, re: RegExp): string | undefined {
  for (const l of leadingMarkers(body)) {
    const m = re.exec(l)
    if (m) return m[1]
  }
  return undefined
}

const lower = (s: unknown) => String(s ?? '').toLowerCase()

/** A comment/PR by one of the pipeline's own bots. A `User` with a bot-like login never counts. */
export function isPipelineBot(c: { user?: GhUser | null } | null | undefined): boolean {
  return c?.user?.type === 'Bot' && PIPELINE_BOTS.some(b => lower(b) === lower(c.user?.login))
}

function stripGeneratedTrailer(body: string): string {
  return body.replace(/\s*-{3,}\s*_Generated by \[Claude Code\]\([^)]*\)_\s*$/, '')
}

/** Drop the regions where a command is shown, not given: fenced blocks, code spans, `>` quotes. */
export function stripNonCommandRegions(body: string | null | undefined): string {
  return stripGeneratedTrailer(String(body ?? ''))
    .replace(/```[\s\S]*?```/g, '')
    .replace(/~~~[\s\S]*?~~~/g, '')
    .replace(/`[^`\n]*`/g, '')
    .split('\n')
    .filter(line => !/^\s*>/.test(line))
    .join('\n')
}

const OWNER_SCREEN_EMOJI = ['🎯', '📐', '🚶', '🗳']

/** The owner-screen emoji the comment opens with (first non-empty line), or null. */
export function ownerScreenEmoji(body: string | null | undefined): string | null {
  const first = String(body || '').split('\n').find(l => l.trim()) || ''
  return OWNER_SCREEN_EMOJI.find(e => first.startsWith(e)) ?? null
}

export function isAgentComment(body: string | null | undefined): boolean {
  const first = String(body || '').split('\n').find(l => l.trim()) || ''
  return /^\s*(?:>\s*)?🤖/u.test(first)
}

const CHECK_ONLY_LINE = /^[ \t]*(?:[✅✔☑]️?[ \t]*)+$/mu
const APPROVAL_WORD = /^[ \t]*(?:lgtm|approved?)(?![\w-])/im
const OK_ONLY_REPLY = /^[ \t\r\n]*ok[\p{P}\p{Extended_Pictographic}\u{FE0F}\u{200D}\s]*$/iu

export function isApproval(body: string | null | undefined): boolean {
  if (isAgentComment(body)) return false
  if (ownerScreenEmoji(body)) return false
  const text = stripNonCommandRegions(body)
  return CHECK_ONLY_LINE.test(text) || OK_ONLY_REPLY.test(text) || APPROVAL_WORD.test(text)
}

export function isNotOk(body: string | null | undefined): boolean {
  if (isAgentComment(body)) return false
  return /^\s*not ok\b/i.test(stripNonCommandRegions(body))
}

/** A real comment typed by the owner (not a bot, not an agent posting from the owner's account). */
export function isOwnerReply(c: GhComment): boolean {
  return lower(c.user?.login) === OWNER_LOGIN && c.user?.type !== 'Bot' && !isAgentComment(c.body)
}

export function isCiFixCommit(k: GhCommit | null | undefined): boolean {
  const msg = k?.commit?.message || ''
  if (!msg.split('\n').some(l => l.trim() === CI_FIX_MARKER)) return false
  return k?.commit?.committer?.name === 'claude[bot]'
}

export type ReviewKind = 'final' | 'round1' | 'failed' | 'needs-owner' | 'other' | 'pending'

/** What the build reviewer last said about THIS head commit — bot comments only, per SHA. */
export function reviewState({ comments = [], headSha, bots = PIPELINE_BOTS }: { comments?: GhComment[], headSha?: string, bots?: string[] }): { kind: ReviewKind, at?: string, comment?: GhComment } {
  const isReviewer = (c: GhComment) => c.user?.type === 'Bot' && bots.some(b => lower(b) === lower(c.user?.login))
  const firstHeading = (body: string) => body.replace(/<!--[\s\S]*?-->/g, '').split('\n').map(l => l.trim()).find(l => l && !l.startsWith('>')) || ''
  const mine = comments
    .filter(isReviewer)
    .map((c) => {
      const body = c.body || ''
      const failed = body.match(BUILD_REVIEW_FAILED_RE)
      const sha = body.match(BUILD_REVIEW_SHA_RE)
      return { c, sha: failed?.[1] || sha?.[1], failed: Boolean(failed && !sha) }
    })
    .filter(x => x.sha && x.sha === headSha)
  if (!mine.length) return { kind: 'pending' }
  const best = mine.reduce((a, b) => (new Date(b.c.created_at) < new Date(a.c.created_at) ? a : b))
  const body = best.c.body || ''
  let kind: ReviewKind
  if (best.failed) kind = 'failed'
  else {
    const verdict = markerValue(body, BUILD_REVIEW_VERDICT_RE)
    if (verdict === 'needs-owner') kind = 'needs-owner'
    else if (verdict !== 'no-go') kind = 'other'
    else kind = body.includes(BUILD_REVIEW_FINAL) || firstHeading(body).startsWith('🔴 **Build rejected twice**') ? 'final' : 'round1'
  }
  return { kind, at: best.c.created_at, comment: best.c }
}

/** Bot-authored plan-review verdicts, oldest first. */
function planVerdicts(comments: GhComment[]): Array<{ v: string, c: GhComment }> {
  const out: Array<{ v: string, c: GhComment }> = []
  for (const c of comments || []) {
    if (c?.user?.type === 'User') continue
    const v = markerValue(c?.body || '', PLAN_VERDICT_RE)
    if (v) out.push({ v, c })
  }
  return out
}

export function isRejectedTwice({ comments = [], labels = [] }: { comments?: GhComment[], labels?: string[] }): boolean {
  if (!labels.includes('status:blocked') || labels.includes('plan:approved')) return false
  const v = planVerdicts(comments).map(x => x.v)
  return v[v.length - 1] === 'no-go' && v.filter(x => x === 'no-go').length >= 2
}

export function isPlanHold({ comments = [], labels = [] }: { comments?: GhComment[], labels?: string[] }): boolean {
  if (!labels.includes('status:blocked') || labels.includes('plan:approved')) return false
  const v = planVerdicts(comments).map(x => x.v)
  return v[v.length - 1] === 'needs-owner' || isRejectedTwice({ comments, labels })
}

/** A real design hold: marker as the first line, or the heading alone on its own line. */
export function isHoldComment(body: string | null | undefined = ''): boolean {
  const b = String(body ?? '')
  return (b.split('\n')[0] ?? '').trim() === DESIGN_HOLD_MARKER || HEADING_OWN_LINE.test(b)
}

/** Which kind of question to the owner is this comment? 'hold' | 'plan' | 'verdict' | null (bot notes). */
export function ownerQuestionKind(body: string | null | undefined = ''): 'plan' | 'verdict' | 'hold' | null {
  const lead: string[] = []
  for (const line of String(body ?? '').split('\n')) {
    if (!line.trim().startsWith('<!--')) break
    lead.push(line.trim())
  }
  if (lead.includes('<!-- pipeline-plan:v1 -->')) return 'plan'
  if (lead.some(l => /^<!-- plan-review-verdict:(go|no-go|needs-owner) -->$/.test(l))) return 'verdict'
  if (isHoldComment(body)) return 'hold'
  return null
}

/** The quiz marker of a comment — `{ pr, sha }` only; the answer key is never read. */
export function readQuizMarker(body: string | null | undefined): { pr: number, sha: string } | null {
  const m = QUIZ_RE.exec(String(body ?? ''))
  if (!m) return null
  return { pr: Number(m[1]), sha: m[2] ?? '' }
}

const QUIZ_TOKEN = /(\d+)\s*(docs|code|intent|[abc?])/gi

/** A comment made ONLY of answer tokens (`1B 2a 3?`) or triage tokens (`2 code`). */
export function isQuizReply(body: string | null | undefined = ''): boolean {
  const s = String(body ?? '').trim()
  if (!s || !/\d/.test(s)) return false
  return s.replace(QUIZ_TOKEN, '').replace(/[\s,;.]/g, '') === '' && [...s.matchAll(QUIZ_TOKEN)].length > 0
}

// ---------------------------------------------------------------- small readers

const commitDate = (k: GhCommit) => k.commit?.committer?.date || k.commit?.author?.date || ''

/** Newest commit that is neither a merge (>1 parent) nor a CI fix — only such a commit voids an `ok`. */
export function newestCountedCommit(commits: GhCommit[] = []): { sha: string, date: string } | null {
  for (let i = commits.length - 1; i >= 0; i--) {
    const k = commits[i]!
    if ((k.parents || []).length > 1 || isCiFixCommit(k)) continue
    return { sha: k.sha, date: commitDate(k) }
  }
  return null
}

/** ISO time of the newest `labeled` event for `label`, or ''. */
export function newestLabeledAt(events: GhEvent[] = [], label: string): string {
  let best = ''
  for (const e of events) {
    if (e.event !== 'labeled' || e.label?.name !== label) continue
    if (!best || new Date(e.created_at) > new Date(best)) best = e.created_at
  }
  return best
}

/** The newest owner question by the pipeline bots, if it is a design hold; else null. */
export function newestDesignHold(comments: GhComment[] = []): GhComment | null {
  const asked = comments
    .filter(isPipelineBot)
    .map(c => ({ c, kind: ownerQuestionKind(c.body) }))
    .filter(x => x.kind)
  const last = asked[asked.length - 1]
  return last?.kind === 'hold' ? last.c : null
}

/** A marker line that is the PR body's own text (not quoted, not in code). */
function bodyHasOwnLine(body: string | null | undefined, marker: string): boolean {
  const text = String(body ?? '').replace(/```[\s\S]*?```/g, '').replace(/~~~[\s\S]*?~~~/g, '')
  return text.split(/\r?\n/).some(l => l.trim() === marker)
}

/** The quiz marker, only when it sits on its own unquoted line outside code. */
function ownQuizMarker(body: string | null | undefined): { pr: number, sha: string } | null {
  const text = String(body ?? '').replace(/```[\s\S]*?```/g, '').replace(/~~~[\s\S]*?~~~/g, '')
  for (const l of text.split(/\r?\n/)) {
    if (/^\s*>/.test(l)) continue
    const hit = readQuizMarker(l)
    if (hit) return hit
  }
  return null
}

/** Statements + their three choices from the visible quiz text. Never the key. */
export function parseQuizQuestions(body: string | null | undefined): Array<{ statement: string, choices: string[] }> {
  const out: Array<{ statement: string, choices: string[] }> = []
  for (const l of String(body ?? '').split(/\r?\n/)) {
    const q = /^\*\*(\d+)\.\*\*\s+(.*\S)\s*$/.exec(l)
    if (q) { out.push({ statement: q[2]!, choices: [] }); continue }
    const c = /^\s*-\s+\*\*([ABC])\*\*\s+—\s+(.*\S)\s*$/.exec(l)
    const cur = out[out.length - 1]
    if (c && cur && cur.choices.length < 3) cur.choices.push(c[2]!)
  }
  return out.filter(q => q.choices.length === 3)
}

const after = (iso: string | null | undefined, since: string) => !!iso && new Date(iso).getTime() > new Date(since).getTime()

function appFromLabels(labels: string[]): string | null {
  for (const l of labels) {
    const m = /^(?:app|poc):(.+)$/.exec(l)
    if (m) return m[1]!
  }
  return null
}

// ---------------------------------------------------------------- collectAsks

export interface CollectInput {
  items: SyncItem[]
  quizItems?: QuizItem[]
}

/**
 * Every waiting ask, one per card. Hold rules (1–6) run in order and an item one rule claims is
 * skipped by the rest; an issue named by a claimed PR's `Closes #N` gets no link card. Delivery
 * (7) and quiz (8) are separate asks on the same epic and do not take part in claiming.
 */
export function collectAsks({ items, quizItems = [] }: CollectInput): { asks: Ask[], unreadable: number[] } {
  const sink = new AskSink()
  const closers = new Set<number>()
  // PRs first, so their `Closes #N` issues are known before the issues are looked at.
  for (const i of items.filter(x => x.isPr)) collectPr(i, sink, closers)
  for (const i of items.filter(x => !x.isPr)) collectIssue(i, sink, closers)
  for (const i of items.filter(isDeliveryItem)) sink.add(i.number, deliveryAsk(i))
  for (const q of quizItems) collectQuiz(q, sink)
  return { asks: sink.asks, unreadable: [...sink.unreadable] }
}

/** Collects asks; an ask with no key or no askedAt is never written — its item counts as unreadable. */
class AskSink {
  asks: Ask[] = []
  unreadable = new Set<number>()
  skip(n: number) { this.unreadable.add(n) }
  add(n: number, a: Ask | null) {
    if (!a) return
    if (!a.sourceCommentId || !validTime(a.askedAt)) this.skip(n)
    else this.asks.push(a)
  }
}

const validTime = (iso: string) => !!iso && !Number.isNaN(new Date(iso).getTime())
const isBlocked = (i: { labels: string[] }) => i.labels.includes('status:blocked')
const isDeliveryItem = (i: SyncItem) => !i.isPr && !i.readError && i.labels.includes('status:to-test')

function collectPr(i: SyncItem, sink: AskSink, closers: Set<number>) {
  if (i.readError) sink.skip(i.number)
  else {
    const hit = holdRules(i) ?? (isBlocked(i) ? { ask: linkAsk(i) } : null)
    if (!hit) return
    sink.add(i.number, hit.ask)
  }
  if (i.closesIssue) closers.add(i.closesIssue)
}

function collectIssue(i: SyncItem, sink: AskSink, closers: Set<number>) {
  if (i.readError) return sink.skip(i.number)
  const hit = holdRules(i)
  if (hit) return sink.add(i.number, hit.ask)
  if (isBlocked(i) && !closers.has(i.number)) sink.add(i.number, linkAsk(i))
}

/** A rule's result: null = the rule does not apply; `{ ask: null }` = claimed, nothing waiting. */
type Hit = { ask: Ask | null } | null
type Rule = (i: SyncItem) => Hit

const base = (i: SyncItem) => ({
  sourceType: (i.isPr ? 'pr' : 'issue') as 'pr' | 'issue',
  sourceNumber: i.number,
  title: i.title,
  link: i.html_url
})

const prKey = (i: SyncItem) => {
  const c = newestCountedCommit(i.commits)
  return { key: c?.sha ?? '', date: c?.date ?? '' }
}

const isVerdict = (body: string | null | undefined) => isApproval(body) || isNotOk(body)

/** 1. sign-off preview — a bot PR with the marker, no owner ok / not ok since the newest counted commit. */
const signoffRule: Rule = (i) => {
  if (!isPipelineBot(i) || !bodyHasOwnLine(i.body, SIGNOFF_PREVIEW_MARKER)) return null
  const { key, date } = prKey(i)
  if (i.comments.some(c => isOwnerReply(c) && isVerdict(c.body) && after(c.created_at, date))) return { ask: null }
  return { ask: { ...base(i), kind: 'review', sourceCommentId: key, ask: 'Look at the preview, then reply ok or not ok.', payload: {}, askedAt: date } }
}

const REVIEW_ASK: Record<string, string> = {
  'final': 'The build review rejected this twice — look at it and reply ok or not ok.',
  'needs-owner': 'The build review needs your call — reply ok or not ok.'
}

/** 2. build-review hold for the owner (`final` or `needs-owner` on the head commit). */
const buildReviewRule: Rule = (i) => {
  const rs = reviewState({ comments: i.comments, headSha: i.headSha })
  const ask = REVIEW_ASK[rs.kind]
  if (!ask) return null
  const { key, date } = prKey(i)
  return { ask: { ...base(i), kind: 'review', sourceCommentId: key, ask, payload: { review: rs.kind }, askedAt: date } }
}

const laterOf = (a: string, b: string) => (!a || !b ? '' : new Date(a) > new Date(b) ? a : b)

/** 3. held for a human merge click (`status:needs-merge`). */
const needsMergeRule: Rule = (i) => {
  if (!i.labels.includes('status:needs-merge')) return null
  const { key, date } = prKey(i)
  const askedAt = laterOf(newestLabeledAt(i.events, 'status:needs-merge'), date)
  return { ask: { ...base(i), kind: 'review', sourceCommentId: key, ask: 'This changes shared code or CI — review it, then reply ok to merge.', payload: {}, askedAt } }
}

/** 4. design sign-off hold — the newest owner question by the bots is the hold. */
const designHoldRule: Rule = (i) => {
  const hold = newestDesignHold(i.comments)
  if (!hold) return null
  const edit = EDIT_LINK_RE.exec(String(hold.body ?? ''))
  const payload: Record<string, unknown> = edit ? { editUrl: edit[1] } : {}
  return { ask: { ...base(i), kind: 'review', sourceCommentId: String(hold.id), ask: 'Look at the design, then reply ok or not ok.', link: hold.html_url || i.html_url, payload, askedAt: hold.created_at } }
}

/** 5. plan held as needs-owner (a plan rejected twice falls through to a link card). */
const planRule: Rule = (i) => {
  const comments = i.comments.filter(isPipelineBot)
  if (!isPlanHold({ comments, labels: i.labels }) || isRejectedTwice({ comments, labels: i.labels })) return null
  const v = planVerdicts(comments)
  const verdict = v[v.length - 1]!.c
  return { ask: { ...base(i), kind: 'review', sourceCommentId: String(verdict.id), ask: 'The plan review needs your call — reply ok or not ok.', link: verdict.html_url || i.html_url, payload: {}, askedAt: verdict.created_at } }
}

const PR_RULES: Rule[] = [signoffRule, buildReviewRule, needsMergeRule]
const BLOCKED_RULES: Rule[] = [designHoldRule, planRule]

/** Hold rules 1–5 in order; the first that applies claims the item. */
function holdRules(i: SyncItem): Hit {
  const rules = [...(i.isPr ? PR_RULES : []), ...(isBlocked(i) ? BLOCKED_RULES : [])]
  for (const rule of rules) {
    const hit = rule(i)
    if (hit) return hit
  }
  return null
}

/** 6. link card — keyed on when `status:blocked` was added. */
function linkAsk(i: SyncItem): Ask {
  const askedAt = newestLabeledAt(i.events, 'status:blocked')
  return { ...base(i), kind: 'issue', sourceCommentId: askedAt, ask: 'This waits on you — open it on GitHub.', payload: {}, askedAt }
}

/** 7. delivery — an epic waiting to be tried. */
function deliveryAsk(i: SyncItem): Ask {
  const askedAt = newestLabeledAt(i.events, 'status:to-test')
  const steps = extractSteps(extractHowToTest(i.body))
  const app = appFromLabels(i.labels)
  const payload: Record<string, unknown> = { steps, to: extractTargetPath(steps) }
  if (app) payload.app = app
  return { ...base(i), kind: 'delivery', sourceCommentId: askedAt, ask: 'Try it, then reply ok or not ok.', payload, askedAt }
}

/** 8. quiz — a bot quiz comment with no later quiz-shaped reply. */
function collectQuiz(q: QuizItem, sink: AskSink) {
  if (q.readError) return sink.skip(q.number)
  q.comments.forEach((c, idx) => {
    const mark = isPipelineBot(c) ? ownQuizMarker(c.body) : null
    if (!mark || q.comments.slice(idx + 1).some(r => isQuizReply(r.body))) return
    sink.add(q.number, {
      kind: 'quiz',
      sourceType: q.isPr ? 'pr' : 'issue',
      sourceNumber: q.number,
      sourceCommentId: String(c.id),
      title: q.title,
      ask: `Quick check — PR #${mark.pr} reached main.`,
      link: c.html_url || q.html_url,
      payload: { pr: mark.pr, questions: parseQuizQuestions(c.body) },
      askedAt: c.created_at
    })
  })
}

