export const cardKey = (c: { sourceType: string, sourceNumber: number, sourceCommentId?: string | null }) =>
  `${c.sourceType}:${c.sourceNumber}:${c.sourceCommentId ?? ''}`

const sameTime = (a: unknown, b: unknown) => new Date(a as string).getTime() === new Date(b as string).getTime()

/** The reply that answered a card whose ask is gone, or null (→ stale). */
function answeringReply(card: ExistingCard, comments: GhComment[]): GhComment | null {
  const since = new Date(card.askedAt).toISOString()
  const answers = REPLY_MATCHERS[card.kind] ?? answersLinkCard
  return comments.find(c => after(c.created_at, since) && answers(c)) ?? null
}

/** A 📐 save / 🎯 preview comment, posted by our app for the owner. */
const isOwnerScreenSave = (c: GhComment) => !!ownerScreenEmoji(c.body) && lower(c.user?.login) === 'nuxt-harness[bot]'
const answersLinkCard = (c: GhComment) => isOwnerReply(c) || isOwnerScreenSave(c)
const REPLY_MATCHERS: Record<string, (c: GhComment) => boolean> = {
  review: c => isOwnerReply(c) && isVerdict(c.body), // a 📐 save never answers a review
  quiz: c => isOwnerReply(c) && isQuizReply(c.body)
}

const askDiffers = (card: ExistingCard, a: Ask) =>
  card.kind !== a.kind || card.title !== a.title || card.ask !== a.ask || card.link !== a.link
  || JSON.stringify(card.payload ?? {}) !== JSON.stringify(a.payload) || !sameTime(card.askedAt, a.askedAt)

/** The patch for a waiting card whose ask is gone: answered (a matching reply) or stale. */
function gonePatch(card: ExistingCard, comments: GhComment[]): CardPatch {
  const reply = answeringReply(card, comments)
  if (!reply) return { state: 'stale' }
  const patch: CardPatch = { state: 'answered', answeredVia: 'github', answeredAt: new Date(reply.created_at) }
  if (reply.html_url) patch.answerUrl = reply.html_url
  if (card.kind === 'review') patch.answer = isApproval(reply.body) ? 'ok' : 'not-ok'
  return patch
}

export function planSync({ asks, unreadable = [], existing, gone = {}, listsComplete }: {
  asks: Ask[]
  unreadable?: number[]
  existing: ExistingCard[]
  gone?: Record<string, { comments: GhComment[] }>
  listsComplete: boolean
}): { create: CardCreate[], update: Array<{ id: string, patch: CardPatch }>, counts: SyncCounts } {
  const skip = new Set(unreadable)
  const byKey = new Map(existing.map(c => [cardKey(c), c]))
  const create: CardCreate[] = []
  const update: Array<{ id: string, patch: CardPatch }> = []
  const counts: SyncCounts = { created: 0, updated: 0, stale: 0, answered: 0 }
  const seen = new Set<string>()

  for (const a of asks.filter(x => !skip.has(x.sourceNumber))) {
    const key = cardKey(a)
    if (seen.has(key)) continue
    seen.add(key)
    const card = byKey.get(key)
    if (!card) {
      create.push({ ...a, state: 'waiting', askedAt: new Date(a.askedAt) })
      counts.created++
    } else if (card.state === 'waiting' && askDiffers(card, a)) { // answered or stale: left as it is
      update.push({ id: card.id, patch: { kind: a.kind, title: a.title, ask: a.ask, link: a.link, payload: a.payload, askedAt: new Date(a.askedAt) } })
      counts.updated++
    }
  }

  for (const card of goneCandidates({ asks, unreadable, existing, listsComplete })) {
    const g = gone[cardKey(card)]
    if (!g) continue // that read failed — leave the card alone
    const patch = gonePatch(card, g.comments)
    update.push({ id: card.id, patch })
    if (patch.state === 'stale') counts.stale++
    else counts.answered++
  }

  return { create, update, counts }
}

/** Waiting cards that need a `since` read to tell answered from stale (empty unless every list loaded). */
export function goneCandidates({ asks, unreadable = [], existing, listsComplete }: {
  asks: Ask[], unreadable?: number[], existing: ExistingCard[], listsComplete: boolean
}): ExistingCard[] {
  if (!listsComplete) return []
  const skip = new Set(unreadable)
  const keys = new Set(asks.map(cardKey))
  return existing.filter(c => c.state === 'waiting' && !skip.has(c.sourceNumber) && !keys.has(cardKey(c)))
}
