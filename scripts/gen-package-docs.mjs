#!/usr/bin/env node
/**
 * Generate packages/<pkg>/docs/components.md: props, events and slots of every component
 * the package's crouton.manifest.ts names (#3933),
 * and packages/<pkg>/docs/llms.txt: an index of the package (description, aiHint, components,
 * composables) from its crouton.manifest.ts, for every package with a manifest (#3980).
 *
 *   node scripts/gen-package-docs.mjs            # write the pages and indexes
 *   node scripts/gen-package-docs.mjs --check    # exit 1 if any page or index is stale or missing (CI)
 *
 * Files come from `node scripts/component-names.mjs --list <pkg>`; props/events/slots from
 * vue-component-meta via scripts/lib/component-meta.mjs.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import { manifestOf } from './lib/read-manifest.mjs'
import { squash, oneLine, code, createReader, componentProps } from './lib/component-meta.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const HEADER = '<!-- Generated by scripts/gen-package-docs.mjs from this package\'s components. Do not edit. -->'
const INDEX_HEADER = '<!-- Generated by scripts/gen-package-docs.mjs from this package\'s manifest. Do not edit. -->'

const cut = s => s.length <= 200 ? s : s.slice(0, 200) + '…'
const typeCell = t => code(cut(squash(t ?? '')))

function fail(msg) {
  process.stderr.write(msg + '\n')
  process.exit(1)
}

/** Packages whose manifest names at least one component, sorted. */
function packagesWithComponents() {
  return readdirSync(join(ROOT, 'packages')).sort().flatMap((pkg) => {
    const rel = `packages/${pkg}/crouton.manifest.ts`
    if (!existsSync(join(ROOT, rel))) return []
    const comps = manifestOf(rel)?.provides?.components ?? []
    return comps.length ? [{ pkg, comps }] : []
  })
}

/** Every package with a crouton.manifest.ts (components or not), sorted. */
function packagesWithManifest() {
  return readdirSync(join(ROOT, 'packages')).sort().flatMap((pkg) => {
    const rel = `packages/${pkg}/crouton.manifest.ts`
    if (!existsSync(join(ROOT, rel))) return []
    return [{ pkg, manifest: manifestOf(rel) ?? {} }]
  })
}

/** The llms.txt index of one package: description, aiHint, components and composables. */
function indexOf({ pkg, manifest }) {
  const pkgName = JSON.parse(readFileSync(join(ROOT, 'packages', pkg, 'package.json'), 'utf8')).name
  const blocks = [`${INDEX_HEADER}\n# ${pkgName}`, `> ${squash(manifest.description ?? '')}`]
  if (manifest.aiHint) blocks.push(`AI hint: ${squash(manifest.aiHint)}`)
  const comps = [...(manifest.provides?.components ?? [])].sort((a, b) => a.name < b.name ? -1 : 1)
  if (comps.length) {
    blocks.push('## Components', comps.map(c => `- \`${c.name}\`: ${squash(c.description ?? '')}`).join('\n'), 'Props, events and slots: [components.md](components.md)')
  }
  const composables = (manifest.provides?.composables ?? []).map(c => typeof c === 'string' ? c : c.name).sort((a, b) => a < b ? -1 : 1)
  if (composables.length) blocks.push('## Composables', composables.map(n => `- \`${n}\``).join('\n'))
  return blocks.join('\n\n') + '\n'
}

/** Name → file (relative to the package folder) from `component-names.mjs --list`. */
function filesOf(pkg) {
  const r = spawnSync('node', ['scripts/component-names.mjs', '--list', pkg], { cwd: ROOT, encoding: 'utf8' })
  if (r.status !== 0) fail(`${pkg}: component-names --list exited ${r.status}\n${r.stderr}`)
  return new Map(r.stdout.split('\n').filter(Boolean).map(l => l.split('\t')))
}

function table(head, rows) {
  if (!rows.length) return null
  return [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map(r => `| ${r.join(' | ')} |`)].join('\n')
}

function componentBlocks(pkg, dir, reader, { name, description }, file) {
  let props, meta
  try {
    props = componentProps(reader, join(dir, file))
    meta = reader.getComponentMeta(join(dir, file))
  } catch (e) {
    fail(`${pkg}: cannot read ${file}: ${String(e?.message ?? e).split('\n')[0]}`)
  }
  const blocks = [`## ${name}`]
  if (description) blocks.push(squash(description))
  blocks.push(`File: \`${file}\``)
  const tables = [
    table(['Prop', 'Type', 'Default', 'Required', 'Description'], props.map(p => [
      code(p.name), typeCell(p.type), p.default === undefined ? '-' : code(squash(p.default)), p.required ? 'yes' : 'no', oneLine(p.doc)
    ])),
    table(['Event', 'Payload'], meta.events.map(e => [code(e.name), typeCell(e.type)])),
    table(['Slot', 'Props'], meta.slots.map(s => [code(s.name), typeCell(s.type)]))
  ].filter(Boolean)
  blocks.push(...(tables.length ? tables : ['No props, events or slots.']))
  return blocks
}

function pageOf({ pkg, comps }) {
  const dir = join(ROOT, 'packages', pkg)
  const pkgName = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).name
  const files = filesOf(pkg)
  const reader = createReader(dir, [join(dir, '**/*.vue')])
  const blocks = [`${HEADER}\n# ${pkgName} components`]
  for (const c of [...comps].sort((a, b) => a.name < b.name ? -1 : 1)) {
    const file = files.get(c.name)
    if (!file) fail(`${pkg}: no file for ${c.name}`)
    blocks.push(...componentBlocks(pkg, dir, reader, c, file))
  }
  return blocks.join('\n\n') + '\n'
}

const pages = packagesWithComponents().map(p => ({ rel: `packages/${p.pkg}/docs/components.md`, text: pageOf(p) }))
const indexes = packagesWithManifest().map(p => ({ rel: `packages/${p.pkg}/docs/llms.txt`, text: indexOf(p) }))

if (CHECK) {
  const stale = [...pages, ...indexes].filter(p => !existsSync(join(ROOT, p.rel)) || readFileSync(join(ROOT, p.rel), 'utf8') !== p.text)
  if (stale.length) {
    for (const p of stale) process.stderr.write(`stale: ${p.rel}\n`)
    fail('Run: node scripts/gen-package-docs.mjs')
  }
  console.log(`${pages.length} package pages and ${indexes.length} index files up to date`)
} else {
  for (const p of [...pages, ...indexes]) {
    mkdirSync(dirname(join(ROOT, p.rel)), { recursive: true })
    writeFileSync(join(ROOT, p.rel), p.text)
  }
  console.log(`wrote ${pages.length} package pages and ${indexes.length} index files`)
}
