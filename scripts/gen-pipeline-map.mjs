#!/usr/bin/env node
/**
 * Generate the "Every workflow, by line" section of docs/pipeline/how-it-works.md (#3730).
 *
 *   node scripts/gen-pipeline-map.mjs            # rewrite the section between the markers
 *   node scripts/gen-pipeline-map.mjs --check    # exit 1 if the page is stale (CI)
 *   ... [--workflows <dir>] [--lines <file>] [--page <file>]
 *
 * Source of truth: each .github/workflows/*.yml (its top-level `name:` and `on:` triggers,
 * read by a plain line scan — Node core only) grouped by scripts/metrics/lines.json (the one
 * grouping; no second list). A workflow missing from lines.json, or a lines.json entry with
 * no file, fails BOTH modes: the map cannot place a file it has no line for.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const START = '<!-- pipeline-map:start -->'
export const END = '<!-- pipeline-map:end -->'
const HEADER = '<!-- GENERATED by scripts/gen-pipeline-map.mjs from .github/workflows + scripts/metrics/lines.json — do not edit by hand -->'

const unquote = s => s.trim().replace(/^(['"])(.*)\1$/, '$2')
const stripComment = s => s.replace(/\s+#.*$/, '').trim()

const ON_KEY = /^(on|"on"|'on'):/

/** The top-level `name:` value, or ''. */
function parseName(lines) {
  const m = lines.map(l => l.match(/^name:\s*(.+)$/)).find(Boolean)
  return m ? unquote(stripComment(m[1])) : ''
}

/** Event keys of a block-form `on:` — the 2-space-indented keys until the next top-level key. */
function blockTriggers(lines, at) {
  const end = lines.findIndex((l, i) => i > at && /^[^\s#]/.test(l))
  return lines.slice(at + 1, end === -1 ? lines.length : end)
    .map(l => l.match(/^ {2}([a-z_]+):/))
    .filter(Boolean)
    .map(m => m[1])
}

/** Triggers from the `on:` key: inline list, inline scalar, or block mapping. */
function parseTriggers(lines) {
  const at = lines.findIndex(l => ON_KEY.test(l))
  if (at === -1) return []
  const rest = stripComment(lines[at].replace(ON_KEY, ''))
  if (rest.startsWith('[')) return rest.replace(/^\[|\]$/g, '').split(',').map(unquote).filter(Boolean)
  if (rest) return [unquote(rest)]
  return blockTriggers(lines, at)
}

/** `{ name, triggers[] }` from a workflow file's text. */
export function parseWorkflow(text) {
  const lines = text.split(/\r?\n/)
  return { name: parseName(lines), triggers: parseTriggers(lines) }
}

const esc = s => String(s).replace(/\|/g, '\\|')

/** Markdown: one `#### <line>` table per lines.json key, rows in lines.json order. */
export function renderSection(lines, workflowsByFile) {
  const out = []
  for (const [line, files] of Object.entries(lines)) {
    out.push(`#### ${line}`, '', '| File | Name | Starts on |', '| --- | --- | --- |')
    for (const f of files) {
      const w = workflowsByFile[f] ?? { name: '', triggers: [] }
      out.push(`| [${f}](../../.github/workflows/${f}) | ${esc(w.name)} | ${w.triggers.map(t => `\`${t}\``).join(', ')} |`)
    }
    out.push('')
  }
  return out.join('\n').trimEnd()
}

/** Files on disk but in no line (`unlisted`), and lines.json entries with no file (`missing`). */
export function diffSets(lines, files) {
  const listed = new Set(Object.values(lines).flat())
  const onDisk = new Set(files)
  return {
    unlisted: [...onDisk].filter(f => !listed.has(f)).sort(),
    missing: [...listed].filter(f => !onDisk.has(f)).sort()
  }
}

/** Replace the marker block in `page`; null when a marker is missing. */
export function fillPage(page, section) {
  const s = page.indexOf(START)
  const e = page.indexOf(END)
  if (s === -1 || e === -1 || e < s) return null
  return `${page.slice(0, s)}${START}\n${HEADER}\n\n${section}\n\n${page.slice(e)}`
}

function arg(argv, flag, dflt) {
  const i = argv.indexOf(flag)
  return i !== -1 && argv[i + 1] ? argv[i + 1] : dflt
}

export function main(argv = process.argv.slice(2), log = console) {
  const check = argv.includes('--check')
  const wfDir = arg(argv, '--workflows', join(ROOT, '.github/workflows'))
  const linesPath = arg(argv, '--lines', join(ROOT, 'scripts/metrics/lines.json'))
  const pagePath = arg(argv, '--page', join(ROOT, 'docs/pipeline/how-it-works.md'))
  const pageLabel = relative(ROOT, pagePath) || pagePath
  const linesLabel = relative(ROOT, linesPath) || linesPath

  const lines = JSON.parse(readFileSync(linesPath, 'utf8')).lines
  const files = readdirSync(wfDir).filter(f => f.endsWith('.yml'))
  const { unlisted, missing } = diffSets(lines, files)
  const problems = [
    ...unlisted.map(f => `not in ${linesLabel}: ${f} — add it to a line`),
    ...missing.map(f => `in ${linesLabel} but no such workflow: ${f} — remove it`)
  ]

  if (!existsSync(pagePath)) { log.error(`${pageLabel} not found`); return 1 }
  const page = readFileSync(pagePath, 'utf8')
  const byFile = Object.fromEntries(files.map(f => [f, parseWorkflow(readFileSync(join(wfDir, f), 'utf8'))]))
  const next = fillPage(page, renderSection(lines, byFile))
  if (next === null) { log.error(`${pageLabel}: missing ${START} / ${END} markers`); return 1 }

  if (check) {
    if (next !== page || problems.length) {
      log.error(`${pageLabel} is out of date — run node scripts/gen-pipeline-map.mjs`)
      for (const p of problems) log.error(`  ${p}`)
      return 1
    }
    log.log(`${pageLabel} is up to date`)
    return 0
  }
  if (problems.length) {
    for (const p of problems) log.error(p)
    return 1
  }
  if (next !== page) writeFileSync(pagePath, next)
  log.log(`wrote ${pageLabel}`)
  return 0
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) process.exit(main())
