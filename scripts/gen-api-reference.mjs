#!/usr/bin/env node
/**
 * Generate docs/content/8.api-reference/{components,composables,field-types,cli}.md from the code.
 *
 *   node scripts/gen-api-reference.mjs            # write the pages
 *   node scripts/gen-api-reference.mjs --check    # exit 1 if any page is stale (CI)
 *
 * Sources (all read statically via the TypeScript AST — nothing is executed):
 *   - components:  packages/crouton-core/app/components/*.vue  (read with vue-component-meta)
 *   - composables: packages/crouton-core/app/composables/*.ts (exported functions + JSDoc)
 *   - field types: packages/{crouton-core,crouton-editor}/crouton.manifest.ts `fieldTypes`,
 *                  plus ALLOWED_META_KEYS in crouton-cli/lib/utils/load-fields.ts
 *   - CLI:         packages/crouton-cli/bin/crouton-generate.js `defineCommand({...})` calls
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = join(ROOT, 'docs/content/8.api-reference')
const require = createRequire(import.meta.url)
const ts = require('typescript')
const { createCheckerByJson } = require('vue-component-meta')

const rd = p => readFileSync(join(ROOT, p), 'utf8')
const sf = (name, text) => ts.createSourceFile(name, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
const jsdoc = (node) => {
  const docs = ts.getJSDocCommentsAndTags(node).filter(ts.isJSDoc)
  const c = docs.length ? docs[docs.length - 1].comment : ''
  const text = typeof c === 'string' ? c : Array.isArray(c) ? c.map(x => x.text ?? '').join('') : ''
  return text.trim()
}
const oneLine = s => s.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim()
const code = s => '`' + String(s).replace(/`/g, "'").replace(/\\?\|/g, '\\|') + '`'

const propKey = p => (ts.isIdentifier(p.name) || ts.isStringLiteralLike(p.name) ? p.name.text : null)
function evalObject(n) {
  const o = {}
  for (const p of n.properties) {
    const k = ts.isPropertyAssignment(p) ? propKey(p) : null
    if (k) o[k] = evalLiteral(p.initializer)
  }
  return o
}
const LITERAL_KEYWORDS = new Map([[ts.SyntaxKind.TrueKeyword, true], [ts.SyntaxKind.FalseKeyword, false]])

const evalScalar = (n) => {
  if (ts.isStringLiteralLike(n)) return n.text
  if (ts.isNumericLiteral(n)) return Number(n.text)
  return LITERAL_KEYWORDS.get(n.kind)
}
const isScalar = n => ts.isStringLiteralLike(n) || ts.isNumericLiteral(n) || LITERAL_KEYWORDS.has(n.kind)

/** Statically evaluate a literal expression (strings, numbers, booleans, arrays, objects). */
function evalLiteral(n) {
  if (!n) return undefined
  if (isScalar(n)) return evalScalar(n)
  if (ts.isArrayLiteralExpression(n)) return n.elements.map(evalLiteral)
  if (ts.isObjectLiteralExpression(n)) return evalObject(n)
  return undefined
}
const walk = (node, fn) => { fn(node); ts.forEachChild(node, c => walk(c, fn)) }

const HEADER = src => `<!-- GENERATED by scripts/gen-api-reference.mjs from ${src} — do not edit; run \`node scripts/gen-api-reference.mjs\`. -->\n`

// ── components ─────────────────────────────────────────────────────────
/** Lead JSDoc of the <script setup> block, minus @example. */
function leadDoc(text) {
  const script = text.match(/<script[^>]*\bsetup\b[^>]*>([\s\S]*?)<\/script>/)?.[1] ?? ''
  const lead = script.match(/^\s*(?:\/\/[^\n]*\n\s*)*\/\*\*([\s\S]*?)\*\//)
  if (!lead) return ''
  return lead[1].split('\n').map(l => l.replace(/^\s*\*\s?/, '')).join('\n').split('@example')[0].trim()
}
// Props come from vue-component-meta (the Volar checker) — no hand-rolled prop parsing.
let checker
function propsOf(file) {
  checker ??= createCheckerByJson(join(ROOT, 'packages/crouton-core'), {
    include: [join(ROOT, COMPONENTS_DIR, '**/*.vue')],
    compilerOptions: { strict: true, skipLibCheck: true, module: 'esnext', moduleResolution: 'bundler', target: 'esnext' }
  }, {})
  const props = checker.getComponentMeta(join(ROOT, file)).props
    .filter(p => !p.global)
    .map(p => ({ name: p.name, type: p.required ? p.type : p.type.replace(/ \| undefined$/, ''), required: p.required, doc: p.description }))
  return { props, doc: leadDoc(rd(file)) }
}

const COMPONENTS_DIR = 'packages/crouton-core/app/components'
const componentFiles = () => [
  ...readdirSync(join(ROOT, COMPONENTS_DIR)).filter(f => f.endsWith('.vue')),
  ...readdirSync(join(ROOT, COMPONENTS_DIR, 'stubs')).filter(f => f.endsWith('.vue')).map(f => 'stubs/' + f)
].sort()
const componentName = (f) => {
  const base = f.replace(/\.vue$/, '').replace(/^stubs\//, '')
  return base.startsWith('Crouton') ? base : 'Crouton' + base
}
function componentSection(name, r) {
  let out = `\n## ${name}\n\n`
  if (r.doc) out += oneLine(r.doc).slice(0, 400) + '\n\n'
  out += '| Prop | Type | Required | Description |\n| --- | --- | --- | --- |\n'
  for (const p of r.props) out += `| ${code(p.name)} | ${code(oneLine(p.type))} | ${p.required ? 'yes' : 'no'} | ${oneLine(p.doc)} |\n`
  return out
}
function genComponents() {
  const dir = COMPONENTS_DIR
  let out = `---\ntitle: Components\ndescription: Props of every crouton-core component (generated from the code)\nicon: i-lucide-layout-grid\n---\n\n${HEADER(dir + '/*.vue')}\n# Components\n\nAuto-imported with the \`Crouton\` prefix (\`Table.vue\` → \`<CroutonTable>\`). Components without props are listed by name only.\n`
  const bare = []
  for (const f of componentFiles()) {
    const name = componentName(f)
    const r = propsOf(`${dir}/${f}`)
    if (!r.props.length) bare.push(name)
    else out += componentSection(name, r)
  }
  if (bare.length) out += `\n## Components without props\n\n${bare.map(n => '- ' + code(n)).join('\n')}\n`
  return out
}

// ── composables ────────────────────────────────────────────────────────
const hasMod = (st, kind) => st.modifiers?.some(m => m.kind === kind)
const KW = ts.SyntaxKind
// Exported functions, default-exported anonymous functions (named after the file),
// `export default useX` and `export const useX = () => ...`.
function localFunctions(s) {
  const decls = new Map()
  for (const st of s.statements) {
    if (ts.isFunctionDeclaration(st) && st.name) decls.set(st.name.text, { name: st.name.text, node: st })
    if (!ts.isVariableStatement(st)) continue
    for (const d of st.declarationList.declarations) {
      const init = d.initializer
      if (ts.isIdentifier(d.name) && init && (ts.isArrowFunction(init) || ts.isFunctionExpression(init))) decls.set(d.name.text, { name: d.name.text, node: init, doc: st })
    }
  }
  return decls
}
// The functions one top-level statement exports, as `[name, node, doc]` tuples.
function exportsOfStatement(st, s, base, decls) {
  if (ts.isFunctionDeclaration(st) && hasMod(st, KW.ExportKeyword)) return [[st.name?.text ?? base, st]]
  if (ts.isVariableStatement(st) && hasMod(st, KW.ExportKeyword)) {
    return st.declarationList.declarations
      .map(d => decls.get(d.name.getText(s)))
      .filter(e => e && /^use[A-Z]/.test(e.name))
      .map(e => [e.name, e.node, st])
  }
  if (ts.isExportAssignment(st) && ts.isIdentifier(st.expression)) {
    const e = decls.get(st.expression.text)
    return e ? [[e.name, e.node, e.doc]] : []
  }
  return []
}
function exportedFunctions(s, file) {
  const base = file.replace(/\.ts$/, '')
  const decls = localFunctions(s)
  const seen = new Set()
  const out = []
  for (const st of s.statements) {
    for (const [name, node, doc] of exportsOfStatement(st, s, base, decls)) {
      if (seen.has(name)) continue
      seen.add(name)
      out.push({ name, node, doc: doc ?? node })
    }
  }
  return out
}
function composableEntry(s, e, dir, f) {
  const st = e.node
  const params = st.parameters.map(p => p.getText(s).replace(/\s+/g, ' ')).join(', ')
  const ret = st.type ? `: ${st.type.getText(s).replace(/\s+/g, ' ')}` : ''
  let out = `\n## ${e.name}\n\n`
  const d = jsdoc(e.doc)
  if (d) out += d.split('\n').filter(l => !l.trim().startsWith('@')).join('\n').trim().split(/\n\n/)[0] + '\n\n'
  return out + `\`\`\`ts\n${e.name}(${params})${ret}\n\`\`\`\n\n_Source: \`${dir}/${f}\`_\n`
}
function genComposables() {
  const dir = 'packages/crouton-core/app/composables'
  const files = readdirSync(join(ROOT, dir)).filter(f => f.endsWith('.ts')).sort()
  let out = `---\ntitle: Composables\ndescription: Every exported crouton-core composable (generated from the code)\nicon: i-lucide-box\n---\n\n${HEADER(dir + '/*.ts')}\n# Composables\n\nAuto-imported. Signatures are read from the source; the description is the JSDoc above each function.\n`
  for (const f of files) {
    const s = sf(f, rd(`${dir}/${f}`))
    for (const e of exportedFunctions(s, f)) out += composableEntry(s, e, dir, f)
  }
  return out
}

// ── field types ────────────────────────────────────────────────────────
function genFieldTypes() {
  const manifests = ['packages/crouton-core/crouton.manifest.ts', 'packages/crouton-editor/crouton.manifest.ts']
  let out = `---\ntitle: Field types\ndescription: Field types a collection schema can use, and the meta keys they accept (generated from the code)\nicon: i-lucide-database\n---\n\n${HEADER(manifests.join(', ') + ', packages/crouton-cli/lib/utils/load-fields.ts')}\n# Field types\n\nThe \`type\` of each field in a schema JSON. Some types only exist when the providing package is extended.\n\n| Type | Aliases | Provided by | SQLite column | TypeScript | Form component | Description |\n| --- | --- | --- | --- | --- | --- | --- |\n`
  for (const m of manifests) {
    const s = sf(m, rd(m))
    let id = ''
    walk(s, (n) => {
      if (ts.isCallExpression(n) && n.expression.getText(s) === 'defineCroutonManifest') {
        const o = evalLiteral(n.arguments[0])
        id = o.id
        for (const [k, v] of Object.entries(o.fieldTypes ?? {})) {
          out += `| ${code(k)} | ${(v.aliases ?? []).map(code).join(', ')} | ${id} | ${code(v.db ?? '')} | ${code(v.tsType ?? '')} | ${code(v.component ?? '')} | ${oneLine(v.description ?? '')} |\n`
        }
      }
    })
  }
  const lf = sf('load-fields.ts', rd('packages/crouton-cli/lib/utils/load-fields.ts'))
  let keys = []
  walk(lf, (n) => {
    if (ts.isVariableDeclaration(n) && n.name.getText(lf) === 'ALLOWED_META_KEYS') {
      walk(n, (m) => { if (ts.isArrayLiteralExpression(m)) keys = evalLiteral(m) })
    }
  })
  out += `\n## Allowed \`meta\` keys\n\nAny other key on a field's \`meta\` is rejected at generate time.\n\n${keys.map(k => '- ' + code(k)).join('\n')}\n`
  return out
}

// ── CLI ────────────────────────────────────────────────────────────────
function genCli() {
  const file = 'packages/crouton-cli/bin/crouton-generate.js'
  const s = sf(file, rd(file))
  let out = `---\ntitle: CLI\ndescription: crouton CLI commands and flags (generated from the code)\nicon: i-lucide-terminal\n---\n\n${HEADER(file)}\n# CLI\n\nRun with \`npx crouton <command>\`.\n`
  walk(s, (n) => {
    if (!(ts.isCallExpression(n) && n.expression.getText(s) === 'defineCommand')) return
    const o = evalLiteral(n.arguments[0])
    if (!o?.meta?.name) return
    out += `\n## ${o.meta.name}\n\n${o.meta.description ?? ''}\n\n`
    const args = Object.entries(o.args ?? {})
    if (!args.length) return
    out += '| Argument | Type | Alias | Default | Description |\n| --- | --- | --- | --- | --- |\n'
    for (const [k, a] of args) {
      const flag = a.type === 'positional' ? `<${k}>` : `--${k}`
      out += `| ${code(flag)} | ${a.type ?? ''} | ${a.alias ? code('-' + a.alias) : ''} | ${a.default !== undefined ? code(a.default) : ''} | ${oneLine(a.description ?? '')} |\n`
    }
  })
  return out
}

const PAGES = {
  'components.md': genComponents,
  'composables.md': genComposables,
  'field-types.md': genFieldTypes,
  'cli.md': genCli
}

const check = process.argv.includes('--check')
let stale = 0
for (const [name, gen] of Object.entries(PAGES)) {
  const path = join(OUT_DIR, name)
  const next = gen().replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
  const cur = existsSync(path) ? readFileSync(path, 'utf8') : null
  if (cur === next) continue
  if (check) { stale++; console.error(`stale: docs/content/8.api-reference/${name}`) } else {
    mkdirSync(OUT_DIR, { recursive: true })
    writeFileSync(path, next)
    console.log(`wrote docs/content/8.api-reference/${name}`)
  }
}
if (check) {
  if (stale) { console.error('Run: node scripts/gen-api-reference.mjs'); process.exit(1) }
  console.log('api-reference pages are up to date')
}
