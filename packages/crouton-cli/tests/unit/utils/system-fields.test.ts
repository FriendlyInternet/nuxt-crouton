import { describe, it, expect } from 'vitest'
import coreManifest from '../../../../crouton-core/crouton.manifest.ts'
import {
  AUTO_GENERATED_FIELDS,
  SYSTEM_FIELD_GROUPS,
  metadataFields,
  autoRefFields,
  hierarchyFields,
  serverManagedFields
} from '../../../lib/utils/system-fields.ts'

// #2286, table 2: the system columns every collection gets were retyped in six
// generators. This module is the ONE enumeration; this file pins it to the core
// manifest so the two can't drift (generators don't hold the loaded manifests, so
// the parity is asserted here rather than read at generate time).
describe('system-fields: one enumeration, pinned to the core manifest', () => {
  it('AUTO_GENERATED_FIELDS equals crouton-core\'s manifest autoGeneratedFields (order included)', () => {
    expect(AUTO_GENERATED_FIELDS).toEqual(coreManifest.autoGeneratedFields)
  })

  it('every system group name is a reserved field name in the manifest', () => {
    const reserved = new Set(coreManifest.reservedFieldNames)
    for (const name of Object.values(SYSTEM_FIELD_GROUPS).flat()) {
      expect(reserved.has(name), `${name} missing from reservedFieldNames`).toBe(true)
    }
  })

  it('metadataFields: timestamps + audit', () => {
    expect(metadataFields()).toEqual(['createdAt', 'updatedAt', 'createdBy', 'updatedBy'])
  })

  it('autoRefFields: owner plus the audit pair', () => {
    expect(autoRefFields()).toEqual(['owner', 'createdBy', 'updatedBy'])
  })

  it('hierarchyFields honours custom names and is empty when hierarchy is off', () => {
    expect(hierarchyFields(undefined)).toEqual([])
    expect(hierarchyFields({ enabled: false })).toEqual([])
    expect(hierarchyFields({ enabled: true })).toEqual(['parentId', 'path', 'depth', 'order'])
    expect(hierarchyFields({ enabled: true, parentField: 'parent', orderField: 'position' })).toEqual(['parent', 'path', 'depth', 'position'])
  })

  it('serverManagedFields is what a PATCH body may never set: every auto field + hierarchy path/depth', () => {
    expect(serverManagedFields()).toEqual(new Set(['id', 'teamId', 'owner', 'createdAt', 'updatedAt', 'createdBy', 'updatedBy', 'path', 'depth']))
  })
})
