// Regenerates src/utils/field-types.snapshot.ts from the CLI manifest loader.
// Run: pnpm --filter @fyit/crouton-mcp snapshot
// tests/field-types.test.ts fails when the committed snapshot drifts from the loader.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { discoverManifests, getAutoGeneratedFields, getTypeMapping } from '../../crouton-cli/lib/utils/manifest-loader.ts'

const manifests = await discoverManifests()
const body = `// GENERATED by scripts/generate-field-types-snapshot.ts — do not edit by hand.
// Fallback used only when the manifest loader cannot be imported at runtime.
import type { FieldTypeMapping } from './field-types.js'

export const FIELD_TYPES_SNAPSHOT: Record<string, FieldTypeMapping> = ${JSON.stringify(getTypeMapping(manifests), null, 2)}

export const AUTO_GENERATED_FIELDS_SNAPSHOT: string[] = ${JSON.stringify(getAutoGeneratedFields(manifests), null, 2)}
`
writeFileSync(fileURLToPath(new URL('../src/utils/field-types.snapshot.ts', import.meta.url)), body)
console.log('wrote field-types.snapshot.ts')
