<template>
  <CroutonFormActionButton
    v-if="action === 'delete'"
    :action="action"
    :collection="collection"
    :items="items"
    :loading="loading"
    @click="handleSubmit"
  />

  <UForm
    v-else
    :schema="schema"
    :state="state"
    @submit="handleSubmit"
    @error="handleValidationError"
  >
    <CroutonFormLayout :tabs="tabs" :navigation-items="navigationItems" :tab-errors="tabErrorCounts" v-model="activeSection">
      <template #main="{ activeSection }">
      <div v-show="!tabs || activeSection === 'general'" class="flex flex-col gap-4 p-1">
        <UFormField :label="t('main.venues.fields.name', 'Name')" name="name" class="not-last:pb-4">
          <UInput v-model="state.name" class="w-full" size="xl" />
        </UFormField>
      </div>

      <div v-show="!tabs || activeSection === 'address'" class="flex flex-col gap-4 p-1">
        <UFormField :label="t('main.venues.fields.street', 'Street')" name="street" class="not-last:pb-4">
          <UInput v-model="state.street" class="w-full" size="xl" />
        </UFormField>
        <UFormField :label="t('main.venues.fields.city', 'City')" name="city" class="not-last:pb-4">
          <UInput v-model="state.city" class="w-full" size="xl" />
        </UFormField>
        <UFormField :label="t('main.venues.fields.postcode', 'Postcode')" name="postcode" class="not-last:pb-4">
          <UInput v-model="state.postcode" class="w-full" size="xl" />
        </UFormField>
       <!-- MapLibre Map Display -->
      <UFormField label="Location Map" name="coordinates" class="not-last:pb-4">
        <CroutonMapsMap
          :center="mapCenter"
          :zoom="14"
          height="400px"
          class="rounded-lg border"
          :fly-to-on-center-change="true"
          @load="handleMapLoad"
        >
          <template #default="{ map }">
            <CroutonMapsMarker
              v-if="mapCenter[0] !== 0 || mapCenter[1] !== 0"
              :map="map as any"
              :position="mapCenter"
              :color="markerColor"
              :options="{ draggable: true }"
              :animate-transitions="true"
              @dragEnd="handleMarkerDragEnd"
            />
          </template>
        </CroutonMapsMap>
        <p v-if="geocoding" class="text-sm text-gray-500 mt-2">
          Geocoding address...
        </p>
      </UFormField>
      </div>
      </template>

      <template #footer>
        <CroutonValidationErrorSummary
          v-if="validationErrors.length > 0"
          :tab-errors="tabErrorCounts"
          :navigation-items="navigationItems"
          @switch-tab="switchToTab"
        />

        <CroutonFormActionButton
          :action="action"
          :collection="collection"
          :items="items"
          :loading="loading"
          :has-validation-errors="validationErrors.length > 0"
        />
      </template>
    </CroutonFormLayout>
  </UForm>
</template>

<script setup lang="ts">
import type { MainVenueFormProps, MainVenueFormData } from '../../types'
import useMainVenues from '../composables/useMainVenues'

const props = defineProps<MainVenueFormProps>()
const { defaultValue, schema, collection } = useMainVenues()

// Field labels resolve through translations (team override → system → fallback)
const { t } = useT()

// Form layout configuration
const navigationItems = [
  { label: 'General', value: 'general' },
  { label: 'Address', value: 'address' }
]

const tabs = ref(true)
const activeSection = ref('general')

// Map field names to their tab groups for error tracking
const fieldToGroup: Record<string, string> = {
  'name': 'general',
  'street': 'address',
  'city': 'address',
  'postcode': 'address'
}

// Track validation errors for tab indicators
const validationErrors = ref<Array<{ name: string; message: string }>>([])

// Handle form validation errors
const handleValidationError = (event: any) => {
  if (event?.errors) {
    validationErrors.value = event.errors
  }
}

// Compute errors per tab
const tabErrorCounts = computed(() => {
  const counts: Record<string, number> = {}

  validationErrors.value.forEach(error => {
    const tabName = fieldToGroup[error.name] || 'general'
    counts[tabName] = (counts[tabName] || 0) + 1
  })

  return counts
})

// Switch to a specific tab (for clicking error links)
const switchToTab = (tabValue: string) => {
  activeSection.value = tabValue
}

// Use new mutation composable for data operations
const { create, update, deleteItems } = useCollectionMutation(collection)

// useCrouton still manages modal state
const { close, loading } = useCrouton()

// Initialize form state with proper values (no watch needed!)
const initialValues = props.action === 'update' && props.activeItem?.id
  ? { ...defaultValue, ...props.activeItem }
  : { ...defaultValue }

// DB nulls are wire/storage values, not form values (#1415): fall back to the
// field default so the strict form schema never sees null on an untouched
// field. No-op when the default itself is null (dates, dependent fields).
const initialRecord = initialValues as Record<string, unknown>
const defaultRecord = defaultValue as Record<string, unknown>
for (const key of Object.keys(defaultRecord)) {
  if (initialRecord[key] === null && defaultRecord[key] !== null) {
    initialRecord[key] = defaultRecord[key]
  }
}

// Draft state: seeded from defaults (required fields may start null/empty until
// the user fills them; the zod schema validates on submit), so cast the initial
// values to the validated shape.
const state = ref<MainVenueFormData & { id?: string | null }>(initialValues as MainVenueFormData & { id?: string | null })
// Map & Geocoding functionality
const { geocode, loading: geocoding } = useGeocode()

// Parse existing coordinates from location field (handle both array and string formats)
const parseCoordinates = (value: any): [number, number] | null => {
  if (!value) return null
  if (Array.isArray(value) && value.length === 2) {
    return [Number(value[0]), Number(value[1])]
  }
  if (typeof value === 'string') {
    try {
      const parsed = JSON.parse(value)
      if (Array.isArray(parsed) && parsed.length === 2) {
        return [Number(parsed[0]), Number(parsed[1])]
      }
    } catch {
      return null
    }
  }
  return null
}

const initialCoordinates = parseCoordinates(state.value.coordinates)
const mapCenter = ref<[number, number]>(initialCoordinates || [0, 0])
const mapInstance = ref<any>(null)

const markerColor = useMarkerColor()

// Store map instance when loaded
const handleMapLoad = (map: any) => {
  mapInstance.value = map
}

// Auto-geocode when address fields change
watchDebounced(
  () => [state.value.street, state.value.city, state.value.postcode],
  async () => {
    if (canGeocode.value) {
      await handleGeocode()
    }
  },
  { debounce: 1000, maxWait: 3000 }
)

// Check if we have enough address data to geocode
const canGeocode = computed(() => {
  return !!state.value.street || !!state.value.city
})

// Handle geocoding of address fields
const handleGeocode = async () => {
  try {
    const addressParts: string[] = []
    if (state.value.street) addressParts.push(state.value.street as string)
    if (state.value.city) addressParts.push(state.value.city as string)
    if (state.value.postcode) addressParts.push(state.value.postcode as string)

    const addressQuery = addressParts.join(', ')
    if (!addressQuery.trim()) return

    const result = await geocode(addressQuery)
    if (result) {
      mapCenter.value = result.coordinates

      // Update the coordinate field in the form state (store as JSON string)
      state.value.coordinates = JSON.stringify(result.coordinates)
    }
  } catch (error) {
    console.error('Geocoding failed:', error)
  }
}

// Handle marker drag to update coordinates
const handleMarkerDragEnd = (position: { lng: number; lat: number }) => {
  mapCenter.value = [position.lng, position.lat]
  state.value.coordinates = JSON.stringify([position.lng, position.lat])
}

const handleSubmit = async () => {
  try {
    if (props.action === 'create') {
      await create(state.value)
    } else if (props.action === 'update' && state.value.id) {
      await update(state.value.id, state.value)
    } else if (props.action === 'delete') {
      await deleteItems(props.items)
    }

    // Clear validation errors on successful submission
    validationErrors.value = []

    close()

  } catch (error) {
    console.error('Form submission failed:', error)
  }
}
</script>